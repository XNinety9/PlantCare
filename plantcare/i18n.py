def get_language(request: Request) -> str:
    cookie = request.cookies.get("lang")
    if cookie in LANGUAGES:
        return cookie
    accept = request.headers.get("accept-language", "").lower()
    return "fr" if accept.startswith("fr") else "en"


def plural(forms: list[str], n: int) -> str:
    return (forms[0] if n == 1 else forms[1]).format(n=n)


def format_date(day: date, lang: str) -> str:
    month = MONTHS[lang][day.month - 1]
    return f"{day.day} {month}" if lang == "fr" else f"{month} {day.day}"


def format_month(day: date, lang: str) -> str:
    return f"{MONTHS_FULL[lang][day.month - 1]} {day.year}"
